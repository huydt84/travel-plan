// APIs return human-readable messages, not stable localization codes. Match known
// messages locally; keep Vietnamese diagnostics intact and localize unknown failures.
export function adminErrorMessage(error, t, locale) {
  const message = error?.message || String(error || "");
  if (locale === "vi") return message || t("adminExtra.error.generic");
  const known = Object.keys(messages.vi).find(
    (key) =>
      messages.vi[key] === message || messages[locale]?.[key] === message,
  );
  if (known) return t(known);
  if (/yêu cầu đang ở trạng thái/.test(message))
    return t("adminExtra.error.requestState");
  const length = message.match(
    /^(\w+) must be a string between (\d+) and (\d+) characters$/,
  );
  if (length) {
    const fields = {
      title: "message209",
      slug: "message166",
      location: "message171",
      label: "message109",
      condition: "message088",
      detail: "message210",
      timezone: "message170",
    };
    return t("adminExtra.error.fieldLength", {
      field: fields[length[1]]
        ? t(`adminExtra.${fields[length[1]]}`)
        : length[1],
      min: length[2],
      max: length[3],
    });
  }
  return t("adminExtra.error.generic");
}
