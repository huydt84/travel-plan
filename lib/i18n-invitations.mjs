// Translate feedback at render time, preserving exact Vietnamese server messages.
export function invitationErrorText(t, locale, error, fallback) {
  if (!error) return "";
  const raw = typeof error === "string" ? error : error.message;
  const key = Object.hasOwn(messages.vi, raw)
    ? raw
    : Object.keys(messages.vi).find((candidate) => messages.vi[candidate] === raw);
  if (key) return t(key);
  const partial = /^Đã gửi (\d+) lời rủ; (\d+) email gửi lỗi\. Kiểm tra lịch sử bên dưới trước khi thử lại\.$/.exec(raw);
  if (partial) return t("invitationsExtra.partialDelivery", { sent: partial[1], failed: partial[2] });
  return locale === "vi" && raw ? raw : t(fallback);
}
