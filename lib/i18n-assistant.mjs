// Batch summaries are generated by the compiler, not authored by the user/model.
export function formatBatchSummary(t, preview) {
  const counts = new Map();
  for (const change of preview.changes) {
    if (!Object.hasOwn(messages.vi, `assistantExtra.summary.${change.kind}`)) return preview.summary;
    counts.set(change.kind, (counts.get(change.kind) || 0) + 1);
  }
  return [...counts].map(([kind, count]) => t(`assistantExtra.summary.${kind}`, { count })).join(", ");
}

// Local error/progress state can outlive a locale change. Resolve only known UI
// messages at render time; never use this helper on authored conversation data.
const interfaceKeys = new Map(Object.values(messages).flatMap((catalog) =>
  Object.entries(catalog).map(([key, value]) => [value, key])));
export function localizeAssistantMessage(t, value) {
  if (typeof value !== "string") return value;
  const requestFailure = /^Request failed \((\d+)\)$/.exec(value);
  if (requestFailure) return t("assistantExtra.error.requestFailed", { status: requestFailure[1] });
  const key = Object.hasOwn(messages.vi, value) ? value : interfaceKeys.get(value);
  return key ? t(key) : value;
}
